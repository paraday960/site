/* -------------------------------------------------------
 * عنوان آرشیوها
 * ----------------------------------------------------- */
function bz_archive_title() {
	if ( is_home() ) { return 'وبلاگ بازار'; }
	if ( is_search() ) { return 'نتایج جست‌وجو برای: «' . get_search_query() . '»'; }
	return get_the_archive_title();
}

/* -------------------------------------------------------
 * تاریخ شمسی ساده برای نمایش (تقریبی، بدون افزونه)
 * ----------------------------------------------------- */
function bz_post_date() {
	$time = get_the_time( 'U' );
	return bz_fa_digits( date_i18n( 'j F Y', $time ) );
}
